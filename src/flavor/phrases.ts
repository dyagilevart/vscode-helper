export function phraseOfTheDay(date = new Date()): string {
  const start = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const dayIndex = Math.floor(start / 86_400_000);
  return PHRASES[((dayIndex % PHRASES.length) + PHRASES.length) % PHRASES.length];
}

export function greetingForHour(hour = new Date().getHours()): string {
  if (hour < 6) {
    return 'Ночная смена в башне';
  }
  if (hour < 12) {
    return 'Доброе утро, разработчик';
  }
  if (hour < 18) {
    return 'Добрый день';
  }
  return 'Добрый вечер';
}
